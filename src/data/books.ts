export const getReviewsForBook = (book: Book): Review[] => {
  const pool = REVIEW_POOL[book.id]
  const seed = book.id.length
  const generated: Review[] = Array.from({ length: 3 }, (_, i) => {
    const person = REVIEW_NAMES[(seed + i * 2) % REVIEW_NAMES.length]
    return {
      id: `${book.id}-r${i}`,
      bookId: book.id,
      name: person.name,
      avatarColor: person.color,
      rating: Math.max(3, Math.round(book.rating - (i % 3) + (i === 0 ? 0.5 : 0))),
      comment: REVIEW_COMMENTS[(seed + i) % REVIEW_COMMENTS.length],
      date: `2025-0${(i % 6) + 1}-${String((seed * 3 + i * 7) % 28 + 1).padStart(2, '0')}`,
    }
  })
  const merged = [
    ...(pool ?? []).map((r, i) => ({ id: `${book.id}-p${i}`, bookId: book.id, ...r })),
    ...generated,
  ]
  return merged.slice(0, 6).sort((a, b) => b.date.localeCompare(a.date))
}

export const formatPrice = (value: number) => `$${value.toFixed(2)}`

export const getBookCardBadge = (book: Book): string | null => {
  if (book.hasDiscount && book.discountPercentage) return `-${book.discountPercentage}%`
  if (book.isNew) return 'NEW!'
  if (book.isBestSeller) return 'BESTSELLER'
  return null
}